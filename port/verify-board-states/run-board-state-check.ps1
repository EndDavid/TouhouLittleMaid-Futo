# Compile the real gomoku / chess engines plus GomokuCodec outside the game and run
# every shipped endgame through them.
#
# This is the gate for "the data pack strings and the codec still agree". A broken
# string only explodes when a player opens a stronghold chest, which is far too late
# to notice, and the same format is what the creative stick exporter writes out.
#
#   powershell -NoProfile -ExecutionPolicy Bypass -File port/verify-board-states/run-board-state-check.ps1
#
# Needs the jars Loom already downloaded, so run gradlew build at least once first.
# Nothing is written back into the repo: the generated data holder and the classes go
# under port/verify-board-states/out, which git ignores.
#
# NOTE: this file is deliberately ASCII-only. Windows PowerShell 5.1 parses a
# BOM-less .ps1 as ANSI, and a UTF-8 comment can swallow the closing quote of the
# next line -- that is not hypothetical, it broke the first version of this script.
$ErrorActionPreference = 'Stop'

$here = $PSScriptRoot
$repo = Split-Path (Split-Path $here -Parent) -Parent
$src = Join-Path $repo 'src\main\java\com\github\tartaricacid\touhoulittlemaid'
$data = Join-Path $repo 'src\main\resources\data\touhou_little_maid\board_states'
$out = Join-Path $here 'out'

function Find-JdkTool([string]$name) {
    $local = Join-Path (Split-Path $repo -Parent) ('jdk-21.0.2\bin\' + $name + '.exe')
    if (Test-Path $local) { return $local }
    return $name
}

$javac = Find-JdkTool 'javac'
$java = Find-JdkTool 'java'

# ---------------------------------------------------------------- classpath
$gradle = Join-Path $env:USERPROFILE '.gradle\caches'
$mc = Get-ChildItem -Path (Join-Path $gradle 'fabric-loom\minecraftMaven') -Recurse -Filter 'minecraft-merged-*.jar' `
    -ErrorAction SilentlyContinue | Where-Object { $_.Name -like '*loom.mappings*' } | Select-Object -First 1
if (-not $mc) {
    throw 'minecraft-merged jar not found; run gradlew build first'
}
$lang3 = Get-ChildItem -Path (Join-Path $gradle 'modules-2') -Recurse -Filter 'commons-lang3-*.jar' `
    -ErrorAction SilentlyContinue | Where-Object { $_.Name -notlike '*sources*' } |
    Sort-Object Name -Descending | Select-Object -First 1
if (-not $lang3) {
    throw 'commons-lang3 jar not found; run gradlew build first'
}
$cp = ($lang3.FullName, $mc.FullName) -join ';'

# ---------------------------------------------------------------- read the data packs
# The files carry // comments (upstream style) and ConvertFrom-Json rejects those,
# so strip them first. No string in these files contains "//", so a line regex is safe.
$arrays = @{}
foreach ($pair in @(@('GOMOKU', 'gomoku'), @('XIANGQI', 'xiangqi'), @('CHESS', 'chess'))) {
    $file = Join-Path $data ($pair[1] + '.json')
    $text = (Get-Content $file -Raw -Encoding UTF8) -replace '(?m)//.*$', ''
    $records = $text | ConvertFrom-Json
    $arrays[$pair[0]] = @($records | ForEach-Object { $_.data })
    Write-Host ('{0,-8} {1} record(s)' -f $pair[1], $arrays[$pair[0]].Count)
}

New-Item -ItemType Directory -Force -Path $out | Out-Null

# ---------------------------------------------------------------- generate the data holder
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// Generated by run-board-state-check.ps1 from the data pack; do not edit.')
[void]$sb.AppendLine('final class BoardStateData {')
foreach ($name in @('GOMOKU', 'XIANGQI', 'CHESS')) {
    [void]$sb.AppendLine('    static final String[] ' + $name + ' = {')
    foreach ($value in $arrays[$name]) {
        $escaped = $value.Replace('\', '\\').Replace('"', '\"')
        [void]$sb.AppendLine('        "' + $escaped + '",')
    }
    [void]$sb.AppendLine('    };')
}
[void]$sb.AppendLine('}')
[System.IO.File]::WriteAllText((Join-Path $out 'BoardStateData.java'), $sb.ToString(),
    (New-Object System.Text.UTF8Encoding($false)))

# ---------------------------------------------------------------- compile
# Only classes that never touch the game's registries: the two engines, the codec,
# and Point (which needs CompoundTag, hence the Minecraft jar on the class path).
$sources = @(
    (Join-Path $src 'api\game\gomoku\GomokuCodec.java'),
    (Join-Path $src 'api\game\gomoku\Point.java'),
    (Join-Path $src 'api\game\xqwlight\Position.java'),
    (Join-Path $src 'api\game\xqwlight\Util.java'),
    (Join-Path $src 'api\game\chess\Position.java'),
    (Join-Path $src 'api\game\chess\Evaluate.java'),
    (Join-Path $src 'api\game\chess\Util.java'),
    (Join-Path $here 'BoardStateCheck.java'),
    (Join-Path $out 'BoardStateData.java')
)
& $javac -nowarn -encoding UTF-8 -d $out -cp $cp $sources
if ($LASTEXITCODE -ne 0) { throw 'javac failed' }

Write-Host ''
& $java -cp ($out + ';' + $cp) BoardStateCheck
if ($LASTEXITCODE -ne 0) { throw 'board state check failed' }

